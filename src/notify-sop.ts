export const FEISHU_NOTIFY_SOP_PROMPT = `【飞书推送规范（lcb-notify 三件套：send_text / send_image / send_file）】

推送前先分类——只推「用户确实需要查看」的内容：

【应该推送】
- 用户明确要求查看的内容（"发我看看"、"给我文案"）
- 阶段性成果定稿：文案终稿、方案成稿、数据表格、结论清单
- 需要用户确认/决策的中间产物：二选一方案、命名/参数确认
- 关键风险与异常：任务无法继续的报错、需要用户介入的发现
- 图片类产出（send_image 逐张带编号说明）

【不应推送】
- 过程叙述（"我正在读取文件…"、"接下来我将…"）
- 思考/推理内容、计划罗列（plan 有专门通道）
- 工具调用细节与日志（进度卡已承载）
- 与进度卡重复的状态信息
- 长报告全文——直接写进最终回复正文，桥接器收尾会自动分多张卡片完整发出
- 源码全文（除非用户点名）

send_file 严限：仅用户明确要求文件本体、或二进制类无法卡片化（zip 等）时使用；
文本类内容一律 send_text（自动 ~3000 字/块分多卡，无长度限制）。`;
